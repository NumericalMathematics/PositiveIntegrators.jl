# Build selected pages of the documentation, e.g., in a persistent Julia session using
# the project `run_agents/docs/` (see `AGENTS.md`):
#   include("/path/to/PositiveIntegrators.jl/utils/build_docs_pages.jl")
#   build_docs_pages("hires_benchmark.md")
# or in the shell from the root of the repository:
#   julia --project=run_agents/docs utils/build_docs_pages.jl hires_benchmark.md
# The given pages of `docs/src/` and `api_reference.md` (the target of most
# cross-references) are copied to a temporary directory and built there with
# Documenter.jl, running all `@example` blocks. Cross-references to other pages cannot be
# resolved and are only reported as warnings, as is the missing landing page `index.md`.
# The HTML output is written to `run_agents/docs/build/`, and figures generated by
# `@example` blocks are saved there as SVG files.

using Documenter: Documenter, DocMeta, makedocs
# `using` all exported names as in `docs/make.jl` to resolve cross-references
using PositiveIntegrators
using JuMP: JuMP # load JuMPExt

const DOCS_SRC_DIR = joinpath(dirname(@__DIR__), "docs", "src")
const REPO_URL = "https://github.com/NumericalMathematics/PositiveIntegrators.jl"
const DOCS_BUILD_DIR = joinpath(dirname(@__DIR__), "run_agents", "docs", "build")

function build_docs_pages(pages::AbstractString...)
    isempty(pages) && throw(ArgumentError("pass the names of the pages to build"))
    pages = unique([collect(pages); "api_reference.md"])
    for page in pages
        isfile(joinpath(DOCS_SRC_DIR, page)) ||
            throw(ArgumentError("page $page not found in $DOCS_SRC_DIR"))
    end

    # GR needs this setting to run without a display
    ENV["GKSwstype"] = "100"
    DocMeta.setdocmeta!(PositiveIntegrators, :DocTestSetup,
                        :(using PositiveIntegrators); recursive = true)
    mktempdir() do root
        mkpath(joinpath(root, "src"))
        for page in pages
            cp(joinpath(DOCS_SRC_DIR, page), joinpath(root, "src", page))
        end
        makedocs(; root, source = "src", build = DOCS_BUILD_DIR,
                 modules = [PositiveIntegrators,
                     Base.get_extension(PositiveIntegrators, :JuMPExt)],
                 sitename = "PositiveIntegrators.jl (selected pages)",
                 format = Documenter.HTML(prettyurls = false, edit_link = nothing,
                                          repolink = REPO_URL,
                                          inventory_version = "selected pages"),
                 pages, remotes = nothing, doctest = false,
                 warnonly = [:missing_docs, :cross_references])
    end
    println("Built ", pages, " in ", DOCS_BUILD_DIR)
    return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
    build_docs_pages(ARGS...)
end
